"""Check the propositions on real KITTI depth maps, pixel for pixel.

    python scripts/verify_theory.py

On every 10th cached frame and all four depth models:
    prop. 1   shadow of lambda * d against that of d (tolerances scaled with the scene)
    prop. 2   shadow with focal factor k against that with the true camera and the equivalent sun s_k
    cor. 3    shadow with focal factor k against that of the depth warp gamma = k (first order only)
Agreement is the IoU of the two rendered road shadows. Writes paper_tits/gen/numbers_verify.tex.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import observability as obs  # noqa: E402
from corruptions import scale_focal, warp  # noqa: E402

import shadows  # noqa: E402

MODELS = ["dav2-s", "dav2-l", "depthpro", "moge2-l"]


def iou(a, b, region):
    a, b = a & region, b & region
    u = (a | b).sum()
    return (a & b).sum() / u if u else np.nan


rows = []
files = sorted((ROOT / "outputs" / "cache").glob("*.npz"))[::10]
for f in files:
    z = np.load(f)
    K, s = z["K"], z["sun"]
    for m in MODELS:
        d = z[f"depth_{m}"].astype(np.float64)
        region = z["receiver"] & (d > 0)
        if region.sum() < 200:
            continue
        base = shadows.render_shadow(d, K, s, only=region)
        if base.sum() < 20:
            continue
        lam = 2.0
        scaled = shadows.render_shadow(lam * d, K, s, max_dist=25.0 * lam, eps=0.15 * lam, thickness=3.0 * lam,
                                       only=region)
        for k in (0.8, 1.25):
            fk = shadows.render_shadow(d, scale_focal(K, k), s, only=region, n_steps=256)
            sk = shadows.render_shadow(d, K, obs.equivalent_sun(s, k), only=region, n_steps=256,
                                       max_dist=25.0 * np.linalg.norm([k * s[0], k * s[1], s[2]]))
            wk = shadows.render_shadow(warp(d, k), K, s, only=region)
            rows.append(dict(key=f.stem, model=m, k=k, scale=iou(base, scaled, region), focal_sun=iou(fk, sk, region),
                             focal_warp=iou(shadows.render_shadow(d, scale_focal(K, k), s, only=region), wk, region),
                             focal_true=iou(fk, base, region)))
df = pd.DataFrame(rows)
out = ROOT / "outputs" / "study" / "verify_theory.csv"
df.to_csv(out, index=False)
print(df.groupby("k")[["scale", "focal_sun", "focal_warp", "focal_true"]].median().round(3))
macros = {"verNCases": f"{df[['key', 'model']].drop_duplicates().shape[0]:d}",
          "verScale": f"{df.scale.median():.2f}", "verFocalSun": f"{df.focal_sun.median():.2f}",
          "verFocalWarp": f"{df.focal_warp.median():.2f}", "verFocalTrue": f"{df.focal_true.median():.2f}"}
(ROOT / "paper_tits" / "gen").mkdir(parents=True, exist_ok=True)
(ROOT / "paper_tits" / "gen" / "numbers_verify.tex").write_text("% generated by scripts/verify_theory.py\n" + "".join(
    f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))
print(macros)
